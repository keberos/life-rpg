export type IconName = keyof typeof MAPS;

// Precompute one SVG path per icon: a 1x1 square for every filled pixel.
const PATHS = Object.fromEntries(
  Object.entries(MAPS).map(([name, rows]) => [
    name,
    rows.flatMap((row, y) => [...row].flatMap((ch, x) => (ch === '#' ? [`M${x} ${y}h1v1h-1z`] : []))).join(''),
  ]),
) as Record<IconName, string>;

export function Icon({ name, size = 18 }: { name: IconName; size?: number }) {
  return (
    <svg class="icon" width={size} height={size} viewBox="0 0 12 12" shape-rendering="crispEdges" aria-hidden="true">
      <path d={PATHS[name]} fill="currentColor" />
    </svg>
  );
}
